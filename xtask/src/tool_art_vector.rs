    let (top, bottom) = if mono {
        ("currentColor", "currentColor")
    } else {
        match a.family {
            "blue" => ("#61B5FF", "#3474B5"),
            "purple" => ("#B293FF", "#7257B8"),
            "grey" => ("#CCD3DF", "#66717F"),
            "green" => ("#64D6A0", "#2A8861"),
            "cyan" => ("#55D6D0", "#287E83"),
            "orange" => ("#FF9C55", "#B95635"),
            "liquify" => ("#EF91BD", "#A24779"),
            "measure" => ("#99B8D6", "#526D8C"),
            _ => ("#CCD3DF", "#66717F"),
        }
    };
    let edge = if mono { "currentColor" } else { "#1b1c20" };
    let shine = if mono { "currentColor" } else { "#F7F9FC" };
    let family = a.family;
    let face = a.face;

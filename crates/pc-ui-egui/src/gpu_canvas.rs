/// Default tile side; documents up to this size (and the device limit) use a single texture.
pub const DEFAULT_TILE: u32 = 8192;
const FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;
/// Canvas texture format of high-bit documents (see [`GpuCanvas::format_for`]).
const FORMAT_HIGH: wgpu::TextureFormat = wgpu::TextureFormat::Rgba16Float;
/// Largest high-bit document (in pixels) given an `Rgba16Float` canvas texture: 100 MP is
/// 800 MB at level 0, about 1.07 GB with mips (twice the `Rgba8Unorm` cost). Bigger 16/32-bit
/// documents (a 14000² one would need 2.1 GB) use `Rgba8Unorm`, so they stay on the GPU like
/// 8-bit ones. `PHOTOCRAFT_CANVAS_F16=0` turns the float canvas off, `=1` ignores this budget.
pub const F16_BUDGET_PX: u64 = 100_000_000;
const VIEW_UNIFORM_SIZE: u64 = 144;
const VIEW_FLOATS: usize = 36;
const TILE_UNIFORM_SIZE: u64 = 32;

/// Parameters for drawing one document view. Positions are in egui points.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ViewParams {
    /// Document key used with [`GpuCanvas::upload_full`].
    pub doc: u64,
    /// Document size in pixels.
    pub doc_size: [u32; 2],
    /// Screen points per document pixel.
    pub zoom: f32,
    /// Document point shown at the centre of the canvas rect.
    pub center: [f32; 2],
    /// Draw the drop shadow on the pasteboard.
    pub shadow: bool,
    /// Draw the pixel grid at high zoom.
    pub pixel_grid: bool,
    /// Distinguishes views painted in the same frame (main canvas, extra windows).
    pub view_key: u64,
    /// Display transform: 0 none, 1 the document's display LUT (document → monitor profile,
    /// Proof Colors), 2 LUT plus the gamut warning (see [`GpuCanvas::set_display_lut`]).
    pub display: u8,
    /// The display the view is on (its LUT is per document and display, #569; 0 = unknown).
    pub output: u32,
    /// View › 32-bit Preview Options (exposure in stops, gamma), applied to the texture values
    /// before the display LUT; `None` when off. The display LUT must then leave it out
    /// (`ColorState::gpu_canvas_lut`).
    pub hdr: Option<[f32; 2]>,
    /// View › Flip Horizontal: the document is drawn mirrored left-right about the view centre
    /// (document x grows to the left).
    pub flip: bool,
    /// Clockwise view rotation in radians; production callers remain upright until activation.
    pub rotation: f32,
}


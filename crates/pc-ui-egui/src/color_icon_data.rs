/// The family hue drawn on dark and on light themes (a lighter and a deeper shade of one hue,
/// carried over from the retired Glossy Duotone families so tools keep their colour coding).
/// `None` for neutral families, which stay in the theme's icon colour.
pub fn family_hue(family: &str) -> Option<(Color32, Color32)> {
    let (dark, light) = match family {
        "blue" => ([0x61, 0xB5, 0xFF], [0x34, 0x74, 0xB5]),
        "yellow" => ([0xEE, 0xC4, 0x66], [0xA7, 0x79, 0x32]),
        "measure" => ([0x99, 0xB8, 0xD6], [0x52, 0x6D, 0x8C]),
        "liquify" => ([0xEF, 0x91, 0xBD], [0xA2, 0x47, 0x79]),
        "green" => ([0x64, 0xD6, 0xA0], [0x2A, 0x88, 0x61]),
        "cyan" => ([0x55, 0xD6, 0xD0], [0x28, 0x7E, 0x83]),
        "purple" => ([0xB2, 0x93, 0xFF], [0x72, 0x57, 0xB8]),
        "orange" => ([0xFF, 0x9C, 0x55], [0xB9, 0x56, 0x35]),
        _ => return None,
    };
    Some((Color32::from_rgb(dark[0], dark[1], dark[2]), Color32::from_rgb(light[0], light[1], light[2])))
}

pub fn family(name: &str) -> Option<&'static str> {
    TOOL_FAMILIES.iter().find(|(n, _)| *n == name).map(|(_, f)| *f)
}

